"""Write results/RESULTS.md: the headline tables of both tiers, generated from the CSVs (no hand-typed numbers).

    python -m efe.evaluation.summary
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from ..scenario import REPO

FILTERS = ["KF", "MO", "EKF-A", "EKF-B", "EKF-B+bias", "EKF-C"]
MAIN = [("rmse_Fxy", "lateral RMSE [N]"), ("rmse_Fz", "F_z RMSE [N]"), ("bias_Fz_end", "F_z bias, low battery [N]"),
        ("noise_F_hover", "hover noise [N]"), ("rise_time", "step rise [s]"), ("detect_delay", "impulse detect [s]"),
        ("k_err_end_pct", "k error [%]"), ("anees_F", "ANEES force (dof 3)")]
EXP_COLS = [("rmse_Fxy_mean", "lateral RMSE [N]"), ("rmse_Fz_mean", "F_z RMSE [N]"), ("bias_Fz_end_mean", "F_z bias end [N]"),
            ("k_err_end_pct_mean", "k error [%]"), ("anees_F_mean", "ANEES force")]


def fmt(m, s):
    if pd.isna(m):
        return "-"
    return f"{m:.3g} ± {s:.2g}" if pd.notna(s) else f"{m:.3g}"


def matrix_table(tier):
    path = REPO / "results" / f"tier{tier}" / "tables" / "summary.csv"
    if not path.exists():
        return f"(no results for tier {tier})\n"
    s = pd.read_csv(path)
    out = []
    for sc in sorted(s["scenario"].unique()):
        out.append(f"\n**{sc}** (mean ± std over seeds 1-4)\n")
        out.append("| filter | " + " | ".join(lab for _, lab in MAIN) + " |")
        out.append("|---|" + "---|" * len(MAIN))
        for f in FILTERS:
            row = []
            for key, _ in MAIN:
                r = s[(s["scenario"] == sc) & (s["filter"] == f) & (s["metric"] == key)]
                row.append(fmt(r["mean"].iloc[0], r["std"].iloc[0]) if len(r) else "-")
            if any(x != "-" for x in row):
                out.append(f"| {f} | " + " | ".join(row) + " |")
    return "\n".join(out) + "\n"


def experiments_table(tier):
    path = REPO / "results" / f"tier{tier}" / "experiments" / "robustness.csv"
    if not path.exists():
        return ""
    r = pd.read_csv(path)
    out = []
    for exp in r["experiment"].unique():
        d = r[r["experiment"] == exp]
        out.append(f"\n**{exp}**\n")
        out.append("| variant | filter | " + " | ".join(lab for _, lab in EXP_COLS) + " |")
        out.append("|---|---|" + "---|" * len(EXP_COLS))
        for _, row in d.iterrows():
            vals = [f"{row[c]:.3g}" if c in row and pd.notna(row[c]) else "-" for c, _ in EXP_COLS]
            out.append(f"| {row['variant']} | {row['filter']} | " + " | ".join(vals) + " |")
    return "\n".join(out) + "\n"


def mc_table(tier):
    path = REPO / "results" / f"tier{tier}" / "experiments" / "replay_mc_consistency.csv"
    if not path.exists():
        return ""
    return "\n" + pd.read_csv(path).to_markdown(index=False, floatfmt=".3g") + "\n"


def main():
    parts = ["# Results\n",
             "Generated by `python -m efe.evaluation.summary` from `results/tier*/`. Seeds 1-4 (seed 0 was the tuning "
             "seed). Tier 0: pure-Python simulator. Tier 1: Isaac Sim + Pegasus + PX4 SITL over uXRCE-DDS, filters "
             "fed from PX4's logged topics. See `docs/FINDINGS.md` for what each number means and what was fixed.\n"]
    for tier, title in [(0, "Tier 0 (Python simulator)"), (1, "Tier 1 (Isaac Sim + Pegasus + PX4 SITL)")]:
        parts.append(f"\n## {title}\n\n### Filters x scenarios\n")
        parts.append(matrix_table(tier))
        parts.append("\n### Robustness and ablation (scenario S1)\n")
        parts.append(experiments_table(tier))
        parts.append("\n### Replay Monte Carlo consistency (50 noise realisations on one truth trajectory)\n")
        parts.append(mc_table(tier))
    dds = REPO / "results" / "tier1" / "tables" / "dds_vs_ulog.csv"
    if dds.exists():
        d = pd.read_csv(dds).groupby("topic").agg(runs=("run", "count"), max_abs_diff=("max_abs_diff", "max"),
                                                  dds_rate_hz=("dds_rate_hz", "mean"))
        parts.append("\n## DDS path check (Tier 1)\n\n" + d.to_markdown(floatfmt=".3g") + "\n")
    out = REPO / "results" / "RESULTS.md"
    out.write_text("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
